/**
 * The shape every language must match.
 *
 * Deliberately not `as const`: with literal types, `Messages` would demand the
 * exact English *strings*, and a Spanish file could never satisfy it. What has
 * to match is the set of keys and the signature of each value — that is what
 * turns a forgotten translation into a compile error.
 */
export type Messages = typeof messages;
